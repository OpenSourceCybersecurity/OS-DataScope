using System.Globalization;
using System.Text;
using System.Text.Encodings.Web;
using DataScope.Api.Reviews;

namespace DataScope.Api.Reports;

/// <summary>Writes a <see cref="ReportDocument"/> as CSV or as a print-ready HTML page.</summary>
internal static class ReportWriters
{
    public static string ContentType(ReportFormat format) => format == ReportFormat.Csv ? "text/csv; charset=utf-8" : "text/html; charset=utf-8";

    public static string FileName(ReportDocument report, ReportFormat format) =>
        $"datascope-{report.Info.Id}{(report.Subject is null ? "" : "-" + report.Subject)}-{report.GeneratedAt.UtcDateTime:yyyyMMdd-HHmm}.{(format == ReportFormat.Csv ? "csv" : "html")}";

    public static Task WriteAsync(ReportDocument report, ReportFormat format, Stream stream, CancellationToken ct) =>
        format == ReportFormat.Csv ? WriteCsvAsync(report, stream, ct) : WriteHtmlAsync(report, stream, ct);

    /// <summary>
    /// The statement first (report, generated, scope, freshness, limitations), a blank line, then the table. Cells go
    /// through <see cref="Csv.Cell"/>, so values from file names or Active Directory cannot become spreadsheet formulas.
    /// </summary>
    public static async Task WriteCsvAsync(ReportDocument report, Stream stream, CancellationToken ct)
    {
        await using var writer = new StreamWriter(stream, Csv.Utf8WithBom, bufferSize: 64 * 1024, leaveOpen: true);
        await writer.WriteAsync(Csv.Line(["Report", report.Info.Title]));
        await writer.WriteAsync(Csv.Line(["Generated (UTC)", report.GeneratedAt]));
        await writer.WriteAsync(Csv.Line(["Generated by", report.GeneratedBy]));
        foreach (var fact in report.Facts)
        {
            await writer.WriteAsync(Csv.Line([fact.Label, fact.Value]));
        }
        foreach (var limit in report.Limitations)
        {
            await writer.WriteAsync(Csv.Line(["Limitation", limit]));
        }
        await writer.WriteAsync(Csv.Line(["Rows", RowsLine(report)]));
        await writer.WriteAsync("\r\n");
        await writer.WriteAsync(Csv.Line(report.Columns));
        foreach (var row in report.Rows)
        {
            ct.ThrowIfCancellationRequested();
            await writer.WriteAsync(Csv.Line(row));
        }
        await writer.FlushAsync(ct);
    }

    /// <summary>
    /// A standalone page: inline styles, no scripts, no external resources, every value HTML-encoded. People print it or
    /// use the browser's "Save as PDF", so no PDF library ships with the product.
    /// </summary>
    public static async Task WriteHtmlAsync(ReportDocument report, Stream stream, CancellationToken ct)
    {
        var e = HtmlEncoder.Default;
        await using var writer = new StreamWriter(stream, new UTF8Encoding(false), bufferSize: 64 * 1024, leaveOpen: true);
        var title = e.Encode(report.Info.Title);
        await writer.WriteAsync($"""
            <!doctype html>
            <html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
            <meta name="robots" content="noindex"><title>{title} · Data Scope</title>
            <style>{Style}</style></head><body>
            <header><div class="brand">Data Scope report</div><h1>{title}</h1><p class="about">{e.Encode(report.Info.About)}</p></header>
            <p class="noprint hint">To keep a copy as a PDF, press Ctrl+P and choose <b>Microsoft Print to PDF</b> or <b>Save as PDF</b>.</p>
            <dl class="facts">
            """);
        await writer.WriteAsync(Fact(e, "Generated", Text(report.GeneratedAt)));
        await writer.WriteAsync(Fact(e, "Generated by", report.GeneratedBy));
        foreach (var fact in report.Facts)
        {
            await writer.WriteAsync(Fact(e, fact.Label, fact.Value));
        }
        await writer.WriteAsync(Fact(e, "Rows", RowsLine(report)));
        await writer.WriteAsync("</dl><section class=\"limits\"><h2>Read this first</h2><ul>");
        foreach (var limit in report.Limitations)
        {
            await writer.WriteAsync($"<li>{e.Encode(limit)}</li>");
        }
        await writer.WriteAsync("</ul></section>");
        if (report.Rows.Count == 0)
        {
            await writer.WriteAsync("<p class=\"empty\">Nothing to report for this scope.</p>");
        }
        else
        {
            await writer.WriteAsync("<table><thead><tr>");
            foreach (var column in report.Columns)
            {
                await writer.WriteAsync($"<th scope=\"col\">{e.Encode(column)}</th>");
            }
            await writer.WriteAsync("</tr></thead><tbody>\n");
            var sb = new StringBuilder();
            foreach (var row in report.Rows)
            {
                ct.ThrowIfCancellationRequested();
                sb.Clear().Append("<tr>");
                foreach (var cell in row)
                {
                    sb.Append(IsNumber(cell) ? "<td class=\"n\">" : "<td>").Append(e.Encode(Text(cell, grouped: true))).Append("</td>");
                }
                sb.Append("</tr>\n");
                await writer.WriteAsync(sb, ct);
            }
            await writer.WriteAsync("</tbody></table>");
        }
        await writer.WriteAsync($"<footer>{title}. Generated by Data Scope on {e.Encode(Text(report.GeneratedAt))} for {e.Encode(report.GeneratedBy)}. Contains information about your organisation's files and permissions: store and share it accordingly.</footer></body></html>\n");
        await writer.FlushAsync(ct);
    }

    public static string RowsLine(ReportDocument report) =>
        report.Truncated
            ? $"{report.Rows.Count:N0} shown. The report stopped at {report.RowLimit:N0} rows and there are more: narrow the scope{(report.RowLimit < ReportLimits.CsvRows ? " or download the CSV, which holds more" : "")}."
            : $"{report.Rows.Count:N0}";

    /// <summary>The same text CSV cells hold, before escaping.</summary>
    public static string Text(object? value, bool grouped = false) => value switch
    {
        null => "",
        DateTimeOffset t => t.UtcDateTime.ToString("yyyy-MM-dd HH:mm 'UTC'", CultureInfo.InvariantCulture),
        DateOnly d => d.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture),
        bool b => b ? "yes" : "no",
        int or long when grouped => ((IFormattable)value).ToString("N0", CultureInfo.InvariantCulture),
        IFormattable f => f.ToString(null, CultureInfo.InvariantCulture),
        _ => value.ToString() ?? "",
    };

    private static bool IsNumber(object? value) => value is int or long or double or decimal;

    private static string Fact(HtmlEncoder e, string label, string value) => $"<dt>{e.Encode(label)}</dt><dd>{e.Encode(value)}</dd>";

    // Print-first: A4 landscape, header row repeated on each page, rows never split. Neutral colours that survive
    // black-and-white printing.
    /// <summary>The printable page's policy: no scripts, no fetching, only its own inline stylesheet (allowed by hash).</summary>
    public static readonly string HtmlContentPolicy =
        $"default-src 'none'; style-src 'sha256-{Convert.ToBase64String(System.Security.Cryptography.SHA256.HashData(Encoding.UTF8.GetBytes(Style)))}'; " +
        "img-src data:; frame-ancestors 'none'; base-uri 'none'; form-action 'none'";

    private const string Style = """
        :root{color-scheme:light;--ink:#1d2329;--ink2:#4a535c;--line:#d5dade;--soft:#f3f5f6;--warn:#fff6dc}
        *{box-sizing:border-box}
        body{margin:0;padding:24px;font:13px/1.45 "Segoe UI",system-ui,-apple-system,sans-serif;color:var(--ink);background:#fff}
        header{border-bottom:2px solid var(--ink);padding-bottom:10px;margin-bottom:14px}
        .brand{font-size:11px;letter-spacing:.08em;text-transform:uppercase;color:var(--ink2)}
        h1{font-size:22px;margin:2px 0 4px}
        h2{font-size:13px;margin:0 0 6px}
        .about{margin:0;color:var(--ink2);max-width:80ch}
        .hint{background:var(--soft);padding:8px 12px;border-radius:6px;max-width:80ch}
        .facts{display:grid;grid-template-columns:max-content 1fr;gap:3px 16px;margin:0 0 14px}
        .facts dt{color:var(--ink2)}
        .facts dd{margin:0}
        .limits{background:var(--warn);border:1px solid #ecd9a0;border-radius:6px;padding:10px 14px;margin-bottom:16px;max-width:110ch}
        .limits ul{margin:0;padding-left:18px}
        table{border-collapse:collapse;width:100%;font-size:11.5px}
        th,td{border:1px solid var(--line);padding:4px 6px;text-align:left;vertical-align:top;min-width:8ch}
        td{overflow-wrap:anywhere}
        th{background:var(--soft);font-weight:600}
        td.n{text-align:right;font-variant-numeric:tabular-nums;white-space:nowrap}
        thead{display:table-header-group}
        tr{break-inside:avoid}
        .empty{color:var(--ink2)}
        footer{margin-top:16px;color:var(--ink2);font-size:11px}
        @page{size:A4 landscape;margin:12mm}
        @media print{body{padding:0}.noprint{display:none}}
        """;
}

/// <summary>Row limits per format. A page with more rows than this is too slow to open or print.</summary>
internal static class ReportLimits
{
    public const int CsvRows = 100_000;
    public const int HtmlRows = 5_000;

    public static int For(ReportFormat format) => format == ReportFormat.Csv ? CsvRows : HtmlRows;
}
