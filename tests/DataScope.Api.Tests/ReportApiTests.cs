    [Fact]
    public async Task A_share_the_scan_could_not_finish_is_a_risk()
    {
        var ops = _lab.Shares["Ops"];
        await using var db = _lab.Database.CreateContext();
        var share = await db.Shares.SingleAsync(s => s.Id == ops);
        var (state, gaps) = (share.State, share.GapCount);
        share.State = DataScope.Persistence.Entities.ShareState.Partial;
        share.GapCount = 2;
        await db.SaveChangesAsync();
        try
        {
            var risk = Assert.Single((await RisksAsync("?rule=not-covered")).Items);
            Assert.Equal(("Low", "2 places in this share were not scanned", ops), (risk.Severity, risk.Title, risk.ShareId!.Value));
            share.State = DataScope.Persistence.Entities.ShareState.Unavailable;
            await db.SaveChangesAsync();
            Assert.Equal("Medium", Assert.Single((await RisksAsync("?rule=not-covered")).Items).Severity);
        }
        finally
        {
            (share.State, share.GapCount) = (state, gaps);
            await db.SaveChangesAsync();
        }
    }

