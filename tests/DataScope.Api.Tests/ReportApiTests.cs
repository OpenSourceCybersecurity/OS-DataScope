    [Fact]
    public async Task Each_role_gets_only_the_reports_it_may_read()
    {
        var all = await (await Admin.GetAsync("/api/v1/reports")).Content.ReadFromJsonAsync<List<ReportInfoView>>();
        // The compliance evidence report needs a standard, so it has its own tests (ComplianceReportTests).
        Assert.Equal([.. ReportIds, "compliance-evidence"], all!.Select(r => r.Id));

        var viewer = Client(Roles.Viewer);
        var forViewer = await (await viewer.GetAsync("/api/v1/reports")).Content.ReadFromJsonAsync<List<ReportInfoView>>();
        Assert.DoesNotContain(forViewer!, r => r.Id is "review-evidence" or "file-activity" or "activity-alerts" or "compliance-evidence");
        Assert.Contains(forViewer!, r => r.Id == "sensitive-data");
        Assert.Equal(HttpStatusCode.Forbidden, (await viewer.GetAsync("/api/v1/reports/review-evidence")).StatusCode);
        Assert.Equal(HttpStatusCode.NotFound, (await Admin.GetAsync("/api/v1/reports/remediation?format=html")).StatusCode);
        Assert.Equal(HttpStatusCode.OK, (await viewer.GetAsync("/api/v1/dashboard")).StatusCode);

        var auditor = Client(Roles.Auditor);
        Assert.Equal(HttpStatusCode.OK, (await auditor.GetAsync("/api/v1/reports/review-evidence")).StatusCode);

        // An owner with no Data Scope role: no reports, no dashboard.
        var person = _lab.Factory.ClientAs("", "S-1-5-21-40-50-60-1101", @"GOV\maria");
        Assert.Empty((await (await person.GetAsync("/api/v1/reports")).Content.ReadFromJsonAsync<List<ReportInfoView>>())!);
        Assert.Equal(HttpStatusCode.Forbidden, (await person.GetAsync("/api/v1/reports/sensitive-data")).StatusCode);
        Assert.Equal(HttpStatusCode.Forbidden, (await person.GetAsync("/api/v1/dashboard")).StatusCode);

        var anonymous = _lab.Factory.ClientAs(null);
        Assert.Equal(HttpStatusCode.Unauthorized, (await anonymous.GetAsync("/api/v1/reports/sensitive-data")).StatusCode);
    }

