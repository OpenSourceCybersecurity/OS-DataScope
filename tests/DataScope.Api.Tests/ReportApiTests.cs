    [Fact]
    public async Task File_names_cannot_become_formulas_in_a_spreadsheet_or_markup_in_the_page()
    {
        var csv = await TextAsync(await Admin.GetAsync("/api/v1/reports/sensitive-data?format=csv"));
        // The file cell starts with the UNC path, so it is safe; the name alone appears in no cell of its own.
        Assert.Contains($@"\\{Host}\Public\{FormulaName}", csv);

        // A cell made only of a hostile value is neutralised by the CSV writer.
        Assert.Equal("'=HYPERLINK(1)", Reviews.Csv.Cell("=HYPERLINK(1)"));
        Assert.Equal("'@SUM(A1)", Reviews.Csv.Cell("@SUM(A1)"));

        var page = await Admin.GetAsync("/api/v1/reports/sensitive-data?format=html");
        var html = await TextAsync(page);
        Assert.DoesNotContain("<img", html);
        Assert.Contains("&lt;img src=x onerror=alert(1)&gt;.csv", html);

        // Even if something slipped through, the page may run no script and load nothing: only its own stylesheet, by hash.
        var csp = page.Headers.GetValues("Content-Security-Policy").Single();
        Assert.StartsWith("default-src 'none'; style-src 'sha256-", csp, StringComparison.Ordinal);
        Assert.DoesNotContain("script-src", csp, StringComparison.Ordinal);
        var style = html[(html.IndexOf("<style>", StringComparison.Ordinal) + 7)..html.IndexOf("</style>", StringComparison.Ordinal)];
        var hash = Convert.ToBase64String(System.Security.Cryptography.SHA256.HashData(Encoding.UTF8.GetBytes(style)));
        Assert.Contains($"'sha256-{hash}'", csp, StringComparison.Ordinal);
    }

