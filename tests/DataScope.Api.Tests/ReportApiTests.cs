    [Fact]
    public async Task A_share_whose_owner_was_disabled_is_a_risk()
    {
        var finance = _lab.Shares["Finance"];
        await using var db = _lab.Database.CreateContext();
        var assignment = await db.OwnerAssignments.SingleAsync(a => a.ShareId == finance && a.EndedAt == null);
        var original = assignment.OwnerSid;
        assignment.OwnerSid = "S-1-5-21-40-50-60-1106"; // tom, disabled in the lab directory
        await db.SaveChangesAsync();
        try
        {
            var risks = await RisksAsync($"?rule=owner-gone");
            var gone = Assert.Single(risks.Items);
            Assert.Equal(finance, gone.ShareId);
            Assert.Equal("The owner's account is disabled", gone.Title);
        }
        finally
        {
            assignment.OwnerSid = original;
            await db.SaveChangesAsync();
        }
        Assert.Empty((await RisksAsync("?rule=owner-gone")).Items);
    }

