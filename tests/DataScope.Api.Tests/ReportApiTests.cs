    private static async Task<string> TextAsync(HttpResponseMessage response)
    {
        var body = await response.Content.ReadAsStringAsync();
        Assert.True(response.IsSuccessStatusCode, $"{(int)response.StatusCode}: {body}");
        return body;
    }

    [Fact]
    public async Task Every_report_states_when_it_was_made_its_scope_and_what_it_cannot_show()
    {
        foreach (var id in ReportIds)
        {
            var response = await Admin.GetAsync($"/api/v1/reports/{id}?format=csv");
            Assert.Equal("text/csv", response.Content.Headers.ContentType?.MediaType);
            Assert.Equal("attachment", response.Content.Headers.ContentDisposition?.DispositionType);
            var bytes = await response.Content.ReadAsByteArrayAsync();
            Assert.True(response.IsSuccessStatusCode, id);
            Assert.Equal(Encoding.UTF8.GetPreamble(), bytes[..3]);
            var csv = Encoding.UTF8.GetString(bytes[3..]);
            Assert.StartsWith("Report,", csv);
            foreach (var fact in new[] { "Generated (UTC),", "Generated by,GOV\\admin", "Scope,All enrolled file servers", "Limitation,", "Rows," })
            {
                Assert.Contains(fact, csv);
            }
            var statement = PeriodReportIds.Contains(id)
                ? new[] { "Period,", "Collection,", "Events missed,", "Security log cleared," }
                : ["Latest scan finished,", "Shares covered,", "Classification policy,", "Active Directory,\"gov.test, synced", "Access resolution,"];
            foreach (var fact in statement)
            {
                Assert.Contains(fact, csv);
            }
            // The statement, a blank line, then the table.
            Assert.Contains("\r\n\r\n", csv);

            var html = await TextAsync(await Admin.GetAsync($"/api/v1/reports/{id}?format=html"));
            Assert.Contains("<h1>", html);
            Assert.Contains("Read this first", html);
            Assert.Contains("All enrolled file servers", html);
            Assert.DoesNotContain("<script", html, StringComparison.OrdinalIgnoreCase);
            Assert.DoesNotContain("http://", html);
            Assert.DoesNotContain("https://", html);
        }
    }

