    [Fact]
    public async Task Risks_put_open_restricted_data_first_and_cover_owners_and_secrets()
    {
        var raw = await TextAsync(await Admin.GetAsync("/api/v1/risks"));
        Assert.DoesNotContain("Synthetic-Only-1", raw); // never the matched text
        var risks = await RisksAsync();
        var first = risks.Items[0];
        Assert.Equal(("open-sensitive", "High", $@"\\{Host}\Public", 3), (first.Rule, first.Severity, first.Where, first.Restricted ?? 0));
        Assert.False(string.IsNullOrWhiteSpace(first.Why));
        Assert.False(string.IsNullOrWhiteSpace(first.Fix));

        // Public holds Restricted files and nobody owns it.
        Assert.Contains(risks.Items, r => r is { Rule: "no-owner", Severity: "Medium" } && r.Where == $@"\\{Host}\Public");
        // The password file sits in Finance, which only the Finance team can read: Medium, not High.
        var secret = Assert.Single(risks.Items, r => r.Rule == "secrets");
        Assert.Equal(("Medium", $@"\\{Host}\Finance", 1), (secret.Severity, secret.Where, secret.Count ?? 0));
        // Quinn is on HR's permissions directly.
        Assert.Contains(risks.Items, r => r.Rule == "direct-user" && r.Who == "quinn");

        Assert.Equal(risks.Items.Count(r => r.Severity == "High"), risks.High);
        Assert.Equal(risks.Items.Count, risks.High + risks.Medium + risks.Low);
        Assert.Equal(risks.Items.Count, risks.Rules.Sum(r => r.High + r.Medium + r.Low));
        Assert.Empty(risks.Limits);
        Assert.False(risks.Truncated);
        Assert.NotNull(risks.LastScanAt);

        // The Risky permissions report lists exactly the permission risks.
        var csv = await TextAsync(await Admin.GetAsync("/api/v1/reports/risky-permissions?format=csv"));
        var permissionRisks = risks.Items.Count(r => r.Rule is "open-sensitive" or "open-change" or "disabled-account" or "deleted-account" or "direct-user" or "unusual-order");
        Assert.Contains($"Rows,{permissionRisks}", csv);
    }

